# ==================== MCI组提示词（轻度认知障碍） ====================
MCI_PROMPT = """生成一段**轻度认知障碍老年人**（MCI组）的家庭对话。

**认知特征**（微妙体现，不要过度）：
- 偶尔出现词语提取困难（"那个...那个东西叫什么来着？"、"就是...嗯...那个..."）
- 轻微的短期记忆问题（刚说过的事可能需要提醒，但不是完全忘记）
- 有时用模糊代词替代具体名词（"那个"、"这个"频率略高，但不是每句都用）
- 偶尔需要重复确认信息（"你刚才说的是...？"）
- 整体逻辑仍然清晰，但偶有小的思维跳跃或需要稍微理清思路
- 可能会说"我想想"、"让我想想"、"哎呀，怎么说呢"等

**重要**：
- MCI是**早期**阶段，大部分时候（70-80%）仍然正常
- 认知问题应该零星出现，不要集中爆发
- 不要让老人显得"很糊涂"，只是"偶尔有点不太顺"
- 家人可能注意到，也可能没注意到，反应要自然

**对话要求**：
- 场景：{scenario}
- 轮数：36轮
- 认知问题的体现要分散在对话中，不要前几轮正常后几轮突然变差
- 老人大部分时候仍然能正常交流
- 家人的反应要真实（可能温和提醒、可能没注意、可能有点担心）
- 对话要有生活气息，不要像在做测试

**真实性要点**：
- 词语提取困难时，老人会停顿、用"那个"、"嗯"、"就是"等填充
- 可能会说"哎呀，年纪大了，记性不好"来自我解释
- 家人可能会说"您说的是XX吗？"来帮助
- 不要让每次遗忘都被明确指出，有些可以自然过渡

**输出格式**（严格JSON）：
{{
  "dialogue": [
    {{"speaker": "elder", "text": "老人的话"}},
    {{"speaker": "family", "text": "家人的话"}},
    ...
  ]
}}
"""

# ==================== ED组提示词（早期痴呆） ====================
ED_PROMPT = """生成一段**早期痴呆老年人**（ED组）的家庭对话。

**认知特征**（明显但不极端）：
- 明显的记忆问题（重复问同一个问题，忘记刚说过的话）
- 时间定向障碍（混淆日期、星期、季节，但不是完全不知道）
- 频繁使用模糊代词（"那个"、"这个"、"他"指代不清，但仍能沟通）
- 话题容易偏离，需要家人引导回来
- 逻辑连贯性下降，但不是完全混乱
- 可能出现轻微的情绪波动或困惑（"我怎么不记得了？"、"是吗？"）
- 可能会重复讲同一件事，或反复确认同一个信息

**重要**：
- 这是**早期**痴呆，不是重度，老人仍能进行基本对话
- 认知问题明显（40-50%的对话中体现），但不是每句话都有问题
- 老人可能意识到自己的问题，会感到困惑或沮丧
- 家人的反应要体现耐心、理解、重复解释

**对话要求**：
- 场景：{scenario}
- 轮数：36轮
- 认知问题应该贯穿对话，但仍有正常交流的时刻
- 家人需要更多地引导、提醒、重复
- 对话要有真实的情感温度（家人的耐心、老人的困惑）
- 不要让对话变成"测试"或"教学"，要保持家庭对话的自然感

**真实性要点**：
- 老人重复提问时，可能用不同的措辞（"今天星期几？"→"现在是周几来着？"）
- 家人重复回答时，语气要自然（"妈，刚跟您说了，今天星期三"）
- 老人可能会说"哦，对对对"、"是吗？我忘了"、"你刚才说什么？"
- 可以有老人试图掩饰记忆问题的表现（"我知道，我就是再确认一下"）
- 家人可能会说"没事，您慢慢想"、"不着急"等安慰的话

**输出格式**（严格JSON）：
{{
  "dialogue": [
    {{"speaker": "elder", "text": "老人的话"}},
    {{"speaker": "family", "text": "家人的话"}},
    ...
  ]
}}
"""

# ==================== 提示词映射 ====================
PROMPT_TEMPLATES = {
    "HC": HC_PROMPT,
    "MCI": MCI_PROMPT,
    "ED": ED_PROMPT
}

def get_prompt(group: str, scenario: str) -> str:
    """
    获取指定组别和场景的提示词
    
    Args:
        group: 认知状态组别 (HC/MCI/ED)
        scenario: 对话场景
    
    Returns:
        格式化后的提示词
    """
    template = PROMPT_TEMPLATES.get(group, HC_PROMPT)
    return template.format(scenario=scenario)